// ApproxDDLNotice 是 CreateStatement 结果开头的声明。
const ApproxDDLNotice = "-- 近似 DDL：由 pg_catalog 重建，不保证与 pg_dump 的输出一致（不含属主、权限、表空间、触发器、规则、行级安全策略、统计目标等）。"

// CreateStatement 用 catalog 拼出表 / 视图的近似建表语句：列（类型、默认值、NOT NULL、IDENTITY / 生成列）、主键 / 唯一 / 外键 / 检查 / 排除约束、
// 独立索引、分区定义、表和列注释。PostgreSQL 没有 SHOW CREATE，所以只是近似（见 ApproxDDLNotice）。
// table 写成 schema.table（不带点按 public）。
func (e *Engine) CreateStatement(ctx context.Context, db, table string) (string, error) {
	schema, name := splitTable(table)
	var sb strings.Builder
	err := e.readTx(ctx, e.dbOrDefault(db), metaTimeout, nil, func(s *session) error {
		rel, err := s.rows(ctx, `SELECT c.oid::text, c.relkind::text, pg_catalog.quote_ident(n.nspname), pg_catalog.quote_ident(c.relname),
       COALESCE(pg_catalog.obj_description(c.oid, 'pg_class'), ''), COALESCE(c.reloptions::text, ''),
       CASE WHEN c.relkind = 'p' THEN pg_catalog.pg_get_partkeydef(c.oid) ELSE '' END,
       CASE WHEN c.relispartition THEN pg_catalog.pg_get_expr(c.relpartbound, c.oid) ELSE '' END,
       COALESCE((SELECT pg_catalog.quote_ident(pn.nspname) || '.' || pg_catalog.quote_ident(pc.relname)
                 FROM pg_catalog.pg_inherits ih JOIN pg_catalog.pg_class pc ON pc.oid = ih.inhparent
                 JOIN pg_catalog.pg_namespace pn ON pn.oid = pc.relnamespace WHERE ih.inhrelid = c.oid LIMIT 1), ''),
       CASE WHEN c.relkind IN ('v', 'm') THEN pg_catalog.pg_get_viewdef(c.oid, true) ELSE '' END
FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = $1 AND c.relname = $2 AND c.relkind IN `+relKinds, schema, name)
		if err != nil {
			return err
		}
		if len(rel) == 0 || len(rel[0]) < 10 {
			return uerr("找不到表或视图 %s.%s", schema, name)
		}
		r := rel[0]
		oid, kind, qn := str(r[0]), str(r[1]), str(r[2])+"."+str(r[3])
		tableComment, reloptions, partKey, partBound, parent, viewDef := str(r[4]), str(r[5]), str(r[6]), str(r[7]), str(r[8]), str(r[9])

		sb.WriteString(ApproxDDLNotice + "\n")
		if kind == "v" || kind == "m" {
			kw := "VIEW"
			if kind == "m" {
				kw = "MATERIALIZED VIEW"
			}
			sb.WriteString("CREATE " + kw + " " + qn + " AS\n" + strings.TrimRight(strings.TrimSpace(viewDef), ";") + ";\n")
			return ddlTail(ctx, s, &sb, oid, qn, kind, tableComment, nil)
		}

		cols, err := s.rows(ctx, `SELECT pg_catalog.quote_ident(a.attname), pg_catalog.format_type(a.atttypid, a.atttypmod), a.attnotnull::text,
       COALESCE(pg_catalog.pg_get_expr(d.adbin, d.adrelid), ''), COALESCE(pg_catalog.to_jsonb(a) ->> 'attidentity', ''),
       COALESCE(pg_catalog.to_jsonb(a) ->> 'attgenerated', ''), COALESCE(pg_catalog.col_description(a.attrelid, a.attnum), '')
FROM pg_catalog.pg_attribute a LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = $1::oid AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, oid)
		if err != nil {
			return err
		}
		cons, err := s.rows(ctx, `SELECT pg_catalog.quote_ident(conname), pg_catalog.pg_get_constraintdef(oid, true)
FROM pg_catalog.pg_constraint WHERE conrelid = $1::oid AND contype IN ('p', 'u', 'f', 'c', 'x')
ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END, conname`, oid)
		if err != nil {
			return err
		}

		kw := "TABLE"
		if kind == "f" {
			kw = "FOREIGN TABLE"
		}
		sb.WriteString("CREATE " + kw + " " + qn + " (\n")
		var lines, colComments []string
		for _, c := range cols {
			if len(c) < 7 {
				continue
			}
			line := "    " + str(c[0]) + " " + str(c[1])
			switch {
			case str(c[5]) == "s":
				line += " GENERATED ALWAYS AS (" + str(c[3]) + ") STORED"
			case str(c[4]) == "a":
				line += " GENERATED ALWAYS AS IDENTITY"
			case str(c[4]) == "d":
				line += " GENERATED BY DEFAULT AS IDENTITY"
			case str(c[3]) != "":
				line += " DEFAULT " + str(c[3])
			}
			if str(c[2]) == "true" {
				line += " NOT NULL"
			}
			lines = append(lines, line)
			if cm := str(c[6]); cm != "" {
				colComments = append(colComments, fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;", qn, str(c[0]), quoteLiteral(cm)))
			}
		}
		for _, c := range cons {
			if len(c) < 2 {
				continue
			}
			lines = append(lines, "    CONSTRAINT "+str(c[0])+" "+str(c[1]))
		}
		sb.WriteString(strings.Join(lines, ",\n"))
		sb.WriteString("\n)")
		if parent != "" && partBound != "" {
			sb.WriteString(" /* 分区子表：PARTITION OF " + parent + " " + partBound + " */") // i18n-ignore: 写进 DDL 文本的注释，属于生成的代码
		}
		if partKey != "" {
			sb.WriteString(" PARTITION BY " + partKey)
		}
		if reloptions != "" { // 形如 {fillfactor=70,autovacuum_enabled=false}
			sb.WriteString(" WITH (" + strings.Trim(reloptions, "{}") + ")")
		}
		if kind == "f" {
			sb.WriteString(" /* 外部表：SERVER 与 OPTIONS 未包含 */") // i18n-ignore: 写进 DDL 文本的注释，属于生成的代码
		}
		sb.WriteString(";\n")
		return ddlTail(ctx, s, &sb, oid, qn, kind, tableComment, colComments)
	})
	if err != nil {
		return "", err
	}
	return sb.String(), nil
}

// ddlTail 追加不属于约束的独立索引，以及表 / 列注释。
func ddlTail(ctx context.Context, s *session, sb *strings.Builder, oid, qn, kind, tableComment string, colComments []string) error {
	idx, err := s.rows(ctx, `SELECT pg_catalog.pg_get_indexdef(i.indexrelid) FROM pg_catalog.pg_index i
WHERE i.indrelid = $1::oid AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint c WHERE c.conindid = i.indexrelid AND c.conrelid = i.indrelid AND c.contype IN ('p', 'u', 'x'))
ORDER BY 1`, oid)
	if err != nil {
		return err
	}
	for _, r := range idx {
		if len(r) > 0 {
			sb.WriteString(str(r[0]) + ";\n")
		}
	}
	if tableComment != "" {
		kw := "TABLE"
		switch kind {
		case "v":
			kw = "VIEW"
		case "m":
			kw = "MATERIALIZED VIEW"
		case "f":
			kw = "FOREIGN TABLE"
		}
		sb.WriteString(fmt.Sprintf("COMMENT ON %s %s IS %s;\n", kw, qn, quoteLiteral(tableComment)))
	}
	for _, c := range colComments {
		sb.WriteString(c + "\n")
	}
	return nil
}

// quoteLiteral 生成 SQL 字符串字面量（standard_conforming_strings=on 下只需要把单引号连写）。
func quoteLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
